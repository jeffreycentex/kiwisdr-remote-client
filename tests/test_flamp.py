"""FLAMP protocol and file-saving regressions, independent of audio hardware."""

import base64
import lzma
from pathlib import Path
import struct
import tempfile
import threading
import unittest

from kiwiremote.flamp import FlampReceiver, FlampWorker, MAX_FILE, crc16, decode_file, safe_filename


def record(kind, body):
    return b"<%s %d %04X>" % (kind.encode(), len(body), crc16(body)) + body


def transfer_frames(payload, name="message.txt", identifier="ABCD", block_size=16):
    prefix = ("{%s}" % identifier).encode()
    count = (len(payload) + block_size - 1) // block_size
    headers = [record("FILE", prefix + b"20261111000000:" + name.encode()),
               record("ID", prefix + b"TEST"),
               record("SIZE", prefix + ("%d %d %d" % (len(payload), count, block_size)).encode())]
    blocks = [record("DATA", ("{%s:%d}" % (identifier, number + 1)).encode()
                     + payload[number * block_size:(number + 1) * block_size])
              for number in range(count)]
    return headers, blocks


class TestFlamp(unittest.TestCase):
    def test_out_of_order_late_fill_and_duplicates(self):
        payload = b"Late blocks fill the original transfer.\n" * 3
        headers, blocks = transfer_frames(payload)
        receiver = FlampReceiver()
        # Provisional blocks may arrive before their metadata.
        for frame in blocks[2:][::-1] + headers:
            for byte in frame:
                receiver.feed(bytes([byte]))
        transfer = receiver.transfers["ABCD"]
        self.assertEqual(transfer.info()["missing"], "1, 2")
        self.assertIsNone(transfer.payload)
        receiver.feed(record("CNTL", b"{ABCD:EOF}"))
        receiver.reset_stream()  # Stopping and restarting Data keeps valid blocks.
        for frame in headers + [blocks[0], blocks[0], blocks[1]]:
            receiver.feed(frame)
        self.assertEqual(transfer.payload, payload)
        self.assertEqual(transfer.info()["missing"], "")
        self.assertEqual(len(transfer.blocks), len(blocks))

    def test_crc_failure_noise_and_resynchronization(self):
        self.assertEqual(crc16(b"123456789"), 0x4b37)
        headers, blocks = transfer_frames(b"This must survive a corrupt block and noise.")
        receiver = FlampReceiver()
        corrupt = bytearray(blocks[1])
        corrupt[-1] ^= 1
        receiver.feed(b"noise<SIZE 9999 1234>" + b"".join(headers) + bytes(corrupt))
        receiver.feed(blocks[0])
        for block in blocks[2:]:
            receiver.feed(block)
        self.assertEqual(receiver.bad_crc, 1)
        self.assertIn("2", receiver.transfers["ABCD"].info()["missing"])
        receiver.feed(blocks[1])
        self.assertIsNotNone(receiver.transfers["ABCD"].payload)

    def test_multiple_transfers_and_conflicting_metadata(self):
        receiver = FlampReceiver()
        for identifier in ("ABCD", "1234"):
            headers, blocks = transfer_frames(b"Different streams", identifier=identifier)
            receiver.feed(b"".join(headers + blocks))
        receiver.feed(record("FILE", b"{ABCD}20261112000000:another.txt"))
        self.assertIn("Conflicting FILE", receiver.transfers["ABCD"].error)
        self.assertEqual(receiver.transfers["1234"].payload, b"Different streams")

    def test_oversized_frames_and_compression_are_rejected(self):
        receiver = FlampReceiver()
        receiver.feed(record("SIZE", b"{ABCD}999999999 65536 64"))
        self.assertIn("oversized", receiver.transfers["ABCD"].error)
        malicious = b"\x01LZMA" + struct.pack(">I", MAX_FILE + 1) + b"\x5d" + struct.pack("<I", 4096)
        with self.assertRaises(ValueError):
            decode_file(malicious)
        receiver.feed(b"x" * 100000)
        self.assertLessEqual(len(receiver.buffer), 48)

    def test_binary_encodings_from_upstream_vectors(self):
        # These escaped vectors were generated by FLAMP's original C++ encoders.
        vectors = [
            (128, b"7\n:0:0  \x18\x10:A:6", bytes(range(7))),
            (256, b"7\n:0:1:2:3:4:5:6", bytes(range(7))),
        ]
        for kind, encoded, expected in vectors:
            envelope = ("[b%d:start]" % kind).encode() + encoded + ("\n[b%d:end]" % kind).encode()
            self.assertEqual(decode_file(envelope), expected)

    def test_base64_lzma_and_plain_files(self):
        original = b"Completed FLAMP package\n" * 100
        filters = [{"id": lzma.FILTER_LZMA1, "dict_size": 1 << 20, "lc": 3, "lp": 0, "pb": 2}]
        compressed = lzma.compress(original, format=lzma.FORMAT_RAW, filters=filters)
        envelope = b"\x01LZMA" + struct.pack(">I", len(original)) + b"\x5d" + struct.pack("<I", 1 << 20) + compressed
        encoded = b"[b64:start]" + base64.b64encode(envelope) + b"\n[b64:end]"
        self.assertEqual(decode_file(encoded), original)
        self.assertEqual(decode_file(original), original)

    def test_exclusive_save_and_safe_names(self):
        payload = b"Saved exactly once per automatic transfer"
        receiver = FlampReceiver()
        headers, blocks = transfer_frames(payload, name="../../message.txt")
        receiver.feed(b"".join(headers + blocks))
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)
            (path / "message.txt").write_bytes(b"existing file")
            saved = Path(receiver.save("ABCD", directory))
            self.assertEqual(saved.parent, path.resolve())
            self.assertEqual(saved.name, "message_1.txt")
            self.assertEqual(saved.read_bytes(), payload)
            self.assertEqual((path / "message.txt").read_bytes(), b"existing file")
        self.assertEqual(safe_filename("C:\\folder\\CON.txt", "ABCD"), "_CON.txt")

    def test_clear_releases_storage_and_failed_save_can_retry(self):
        receiver = FlampReceiver()
        headers, blocks = transfer_frames(b"Kept for retry")
        receiver.feed(b"".join(headers + blocks))
        with tempfile.TemporaryDirectory() as directory:
            not_directory = Path(directory) / "occupied"
            not_directory.write_bytes(b"existing")
            with self.assertRaises(OSError):
                receiver.save("ABCD", not_directory)
            self.assertEqual(receiver.transfers["ABCD"].payload, b"Kept for retry")
            receiver.save("ABCD", Path(directory) / "received")
            receiver.clear("ABCD")
            self.assertEqual(receiver.stored_bytes, 0)
            self.assertTrue((Path(directory) / "received/message.txt").exists())

    def test_worker_late_fill_autosaves_once(self):
        saved = threading.Event()
        events = []

        def on_event(kind, value):
            events.append((kind, value))
            if kind == "flamp_transfers" and any(item["path"] for item in value):
                saved.set()

        headers, blocks = transfer_frames(b"Verified file body\n" * 10)
        with tempfile.TemporaryDirectory() as directory:
            worker = FlampWorker(on_event)
            try:
                worker.submit("configure", (directory, True))
                worker.feed(b"".join(headers + blocks[1:]))
                worker.submit("reset")
                worker.feed(b"".join(headers + [blocks[0]]))
                self.assertTrue(saved.wait(5), events)
                worker.feed(b"".join(headers + blocks))
            finally:
                worker.close()
            self.assertEqual([path.name for path in Path(directory).iterdir()], ["message.txt"])
            self.assertEqual((Path(directory) / "message.txt").read_bytes(), b"Verified file body\n" * 10)
